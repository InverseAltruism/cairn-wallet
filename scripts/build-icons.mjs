#!/usr/bin/env node
// Writes src/popup/icons.svg, the popup's one SVG sprite: the Lucide icons the pages use (ISC, from the
// lucide-static package at the version below); and src/popup/icons.LICENSE.txt, the package's
// LICENSE verbatim (ISC, with the MIT notice for the icons derived from Feather), which build.mjs ships beside it. Usage, from an unpacked lucide-static tarball
// whose npm integrity was checked:
//   node scripts/build-icons.mjs <lucide-static package dir>
// The pages reference a symbol as <svg class="i"><use href="icons.svg#i-<name>"/></svg>; stroke width and size
// come from popup.css, so the symbols carry no stroke-width. The Cairn mark is not in the sprite: the pages draw the
// vendored cairn-ui file, <svg viewBox="300 330 590 530"><use href="ui/mark.svg#mark"/></svg> (test/mark-home.test.mjs).
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const LUCIDE_VERSION = "1.54.0";
const ICONS = [
  "arrow-up-right", "arrow-down-left", "arrow-left-right", "ellipsis", "settings-2", "lock", "chevron-down", "x",
  "refresh-cw", "users", "key-round", "scroll-text", "message-square-text", "stamp", "plus",
  "check", "coins", "shield-check", "triangle-alert", "octagon-alert", "info", "chevron-right", "external-link",
];
const dir = process.argv[2];
if (!dir) throw new Error("usage: node scripts/build-icons.mjs <lucide-static package dir>");
const pkg = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
if (pkg.name !== "lucide-static" || pkg.version !== LUCIDE_VERSION) throw new Error(`expected lucide-static ${LUCIDE_VERSION}, got ${pkg.name} ${pkg.version}`);

function inner(name) {
  const svg = readFileSync(join(dir, "icons", `${name}.svg`), "utf8");
  const body = svg.slice(svg.indexOf(">", svg.indexOf("<svg")) + 1, svg.lastIndexOf("</svg>"));
  return body.split("\n").map((l) => l.trim()).filter(Boolean).join("").replace(/\s*\/>/g, "/>");
}

const symbols = ICONS.map((n) => `<symbol id="i-${n}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-linecap="round" stroke-linejoin="round">${inner(n)}</symbol>`);
const out = [
  '<svg xmlns="http://www.w3.org/2000/svg">',
  `<!-- Icons i-*: Lucide ${LUCIDE_VERSION} (lucide-static, https://lucide.dev); licence in icons.LICENSE.txt. Generated by scripts/build-icons.mjs. -->`,
  ...symbols,
  "</svg>",
  "",
].join("\n");
writeFileSync(join(import.meta.dirname, "..", "src", "popup", "icons.svg"), out);
writeFileSync(join(import.meta.dirname, "..", "src", "popup", "icons.LICENSE.txt"), readFileSync(join(dir, "LICENSE")));
console.log(`icons.svg: ${ICONS.length} Lucide ${LUCIDE_VERSION} icons`);
