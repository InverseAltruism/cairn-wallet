#!/usr/bin/env node
// Generates and checks src/core/spvanchors.ts, the release anchor table (cairn docs/Plans/86, section 3.3).
//
// Generate, on the deploy host, from the corroborated anchor that cairn's bump-swapguard-cp.mjs --emit-json prints:
//   node scripts/update-spv-anchors.mjs <anchor.json> [--write]        HEADERS_BASE defaults to http://127.0.0.1:7777
// Check, in CI against hosts the deploy host does not control (the release.yml `anchors` job):
//   node scripts/update-spv-anchors.mjs --check --headers https://clarvis.cairn-substrate.com --rpc https://cairn-substrate.com/api/rpc
//
// Both modes walk the served headers up from the table's own floor pin through the vendored LightClient (hash,
// prev link, time rules, LWMA bits, PoW), so every entry is the hash the walk reaches at its height, not a
// served one. Generate writes nothing unless every check passes and the walk reaches the corroborated hash.
// SPV_FLOOR is carried forward from the committed table, not derived from served data.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { LightClient } from "../src/vendor/cairnx-spv.js";

export const CHUNK = 4096;
export const PAGE = 512;
export const MIN_MARGIN = 1000;
export const MAX_LAG = 6000;
const HASH_RE = /^0x[0-9a-f]{64}$/;
const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
export const TABLE = join(ROOT, "src", "core", "spvanchors.ts");

export const firstChunk = (floor, chunk) => Math.floor(floor.height / chunk);
export const topOf = (k, chunk) => k * chunk + chunk - 1;

/** Parses and checks the cairn C1 JSON line; returns { height, hash, tip } or throws naming the failed rule. */
export function validateC1(text, chunk, floor) {
  let j;
  try { j = JSON.parse(String(text).trim()); } catch { throw new Error("anchor JSON is empty or not JSON (bump-swapguard-cp refused?)"); }
  const src = Array.isArray(j?.sources) ? j.sources : [];
  const role = (r) => src.find((s) => s?.role === r);
  const rules = [
    ["v must be 1", j?.v === 1],
    ["exactly three sources: node, miner, third", src.length === 3 && ["node", "miner", "third"].every((r) => src.filter((s) => s?.role === r).length === 1)],
    ["every source must answer yes", src.length === 3 && src.every((s) => s?.answer === "yes")],
    ["the third source must be routed to its primary backend", role("third")?.routing === "primary"],
    [`margin must be at least ${MIN_MARGIN}`, Number.isSafeInteger(j?.margin) && j.margin >= MIN_MARGIN],
    [`height must be at least ${MIN_MARGIN} below tip`, Number.isSafeInteger(j?.height) && Number.isSafeInteger(j?.tip) && j.height <= j.tip - MIN_MARGIN],
    ["hash must be 0x and 64 lowercase hex", typeof j?.hash === "string" && HASH_RE.test(j.hash)],
    [`height must be a chunk top (${chunk}k + ${chunk - 1})`, j?.height % chunk === chunk - 1],
    ["height must be at or above the first chunk top", j?.height >= topOf(firstChunk(floor, chunk), chunk)],
  ];
  const bad = rules.find(([, ok]) => !ok);
  if (bad) throw new Error(`anchor JSON refused: ${bad[0]}`);
  return { height: j.height, hash: j.hash, tip: j.tip };
}

export function renderTable({ floor, chunk, anchors }) {
  const k0 = firstChunk(floor, chunk);
  return [
    "// Generated by scripts/update-spv-anchors.mjs (usage at its top); do not edit.",
    `// SPV_ANCHORS[i] is the block hash at height SPV_CHUNK * (${k0} + i) + SPV_CHUNK - 1.`,
    `export const SPV_FLOOR = { height: ${floor.height}, hash: "${floor.hash}" } as const;`,
    `export const SPV_CHUNK = ${chunk};`,
    "export const SPV_ANCHORS: readonly string[] = [",
    ...anchors.map((h, i) => `  "${h}", // ${topOf(k0 + i, chunk)}`),
    "];",
    "",
  ].join("\n");
}

/** Strict inverse of renderTable: a file that does not re-render byte for byte was edited by hand. */
export function parseTable(text) {
  const floorM = /export const SPV_FLOOR = \{ height: (\d+), hash: "(0x[0-9a-f]{64})" \} as const;/.exec(text);
  const chunkM = /export const SPV_CHUNK = (\d+);/.exec(text);
  if (!floorM || !chunkM) throw new Error("spvanchors.ts: SPV_FLOOR or SPV_CHUNK line not found");
  const floor = { height: Number(floorM[1]), hash: floorM[2] };
  const chunk = Number(chunkM[1]);
  const anchors = [...text.matchAll(/^ {2}"(0x[0-9a-f]{64})", \/\/ \d+$/gm)].map((m) => m[1]);
  const t = { floor, chunk, anchors };
  if (renderTable(t) !== text) throw new Error("spvanchors.ts does not match the generator's output (hand-edited?)");
  return t;
}

// Retry-After-paced JSON GET. A 3xx is an error: a source must not answer from another host.
export async function getJson(url, { fetch = globalThis.fetch, sleep = defaultSleep } = {}) {
  for (let attempt = 0; ; attempt++) {
    const r = await fetch(url, { redirect: "error", signal: AbortSignal.timeout(30_000) });
    if ((r.status === 429 || r.status === 502 || r.status === 503) && attempt < 8) {
      const ra = Number(r.headers.get("retry-after"));
      await sleep(Math.min(Number.isFinite(ra) && ra > 0 ? ra * 1000 : 2000 * (attempt + 1), 120_000));
      continue;
    }
    if (!r.ok) throw new Error(`${url} -> ${r.status}`);
    return r.json();
  }
}
const defaultSleep = (ms) => new Promise((r) => setTimeout(r, ms));

/** One page-aligned /api/headers range, exactly `pageSize` rows at consecutive heights, or a throw. */
export async function fetchPage(base, from, pageSize, io) {
  const d = await getJson(`${base.replace(/\/$/, "")}/api/headers/${from}/${pageSize}`, io);
  const rows = d?.headers;
  if (!Array.isArray(rows) || rows.length !== pageSize) throw new Error(`/api/headers/${from}/${pageSize}: ${Array.isArray(rows) ? rows.length : "no"} rows, want ${pageSize}`);
  rows.forEach((row, i) => {
    if (row?.height !== from + i || typeof row.hash !== "string" || !row.header) throw new Error(`/api/headers/${from}/${pageSize}: row ${i} is not height ${from + i}`);
  });
  return rows;
}

/** Walks from the floor pin to max(tops); returns the walked hash at each top. */
export async function walkTops({ floor, tops, base, pageSize = PAGE, paceMs = 550, io = {} }) {
  const sleep = io.sleep ?? defaultSleep;
  const pages = new Map();
  const row = async (h) => {
    const p = h - (h % pageSize);
    if (!pages.has(p)) {
      if (pages.size) await sleep(paceMs);
      pages.set(p, await fetchPage(base, p, pageSize, io));
    }
    return pages.get(p)[h - p];
  };
  const batch = async (from, count) => {
    const out = [];
    for (let h = from; h < from + count; h++) { const r = await row(h); out.push({ header: r.header, hash: r.hash }); }
    return out;
  };
  const lc = new LightClient({ headersBatchProvider: batch, checkpoints: { [floor.height]: floor.hash } });
  await lc.syncFromCheckpoint(floor.height, floor.hash);
  await lc.sync(Math.max(...tops));
  return tops.map((h) => String(lc.at(h).hash).toLowerCase());
}

/** Generate mode. Returns the new table text; writes it only with write=true and only after every check. */
export async function generate({ c1Text, tablePath = TABLE, base, write = false, chunk = CHUNK, pageSize = PAGE, paceMs, io }) {
  const old = parseTable(readFileSync(tablePath, "utf8"));
  if (old.chunk !== chunk) throw new Error(`committed SPV_CHUNK ${old.chunk} != generator chunk ${chunk}`);
  const target = validateC1(c1Text, chunk, old.floor);
  const k0 = firstChunk(old.floor, chunk);
  const tops = [];
  for (let k = k0; topOf(k, chunk) <= target.height; k++) tops.push(topOf(k, chunk));
  const anchors = await walkTops({ floor: old.floor, tops, base, pageSize, paceMs, io });
  if (anchors[anchors.length - 1] !== target.hash) throw new Error(`the walk from the floor pin reaches ${anchors[anchors.length - 1]} at ${target.height}, not the corroborated ${target.hash}; nothing written`);
  const drift = old.anchors.findIndex((h, i) => anchors[i] !== h);
  if (old.anchors.length > anchors.length || drift >= 0) throw new Error(`the new table does not extend the committed one (first difference at entry ${drift >= 0 ? drift : anchors.length}); nothing written`);
  const text = renderTable({ floor: old.floor, chunk, anchors });
  if (write) writeFileSync(tablePath, text);
  return { text, entries: anchors.length, newest: target.height };
}

// Tri-state on purpose: "says another hash" and "cannot answer" are different facts; the check needs "yes".
export async function canonicalAt(rpc, height, hash, io) {
  let d;
  try { d = await getJson(`${rpc.replace(/\/$/, "")}/block/height/${height}`, io); } catch { return "unreachable"; }
  if (d?.ok !== true || typeof d.hash !== "string") return "unreachable";
  return d.height === height && String(d.hash).toLowerCase() === hash ? "yes" : "no";
}

/** Check mode: every committed entry equals the walk from `headers` and is canonical at `rpc`; the newest is fresh. */
export async function check({ tablePath = TABLE, headers, rpc, pageSize = PAGE, paceMs = 550, io = {} }) {
  if (!headers || !rpc) throw new Error("--check needs --headers <base> and --rpc <base>");
  const t = parseTable(readFileSync(tablePath, "utf8"));
  if (!t.anchors.length) throw new Error("spvanchors.ts has no entries");
  const k0 = firstChunk(t.floor, t.chunk);
  const tops = t.anchors.map((_, i) => topOf(k0 + i, t.chunk));
  const walked = await walkTops({ floor: t.floor, tops, base: headers, pageSize, paceMs, io });
  const bad = walked.findIndex((h, i) => h !== t.anchors[i]);
  if (bad >= 0) throw new Error(`entry ${bad} (height ${tops[bad]}) is ${t.anchors[bad]}, the walk from ${headers} reaches ${walked[bad]}`);
  for (let i = 0; i < tops.length; i++) {
    await (io.sleep ?? defaultSleep)(paceMs);
    const a = await canonicalAt(rpc, tops[i], t.anchors[i], io);
    if (a !== "yes") throw new Error(`${rpc} answers "${a}" for entry ${i} at height ${tops[i]}`);
  }
  const tip = Number((await getJson(`${rpc.replace(/\/$/, "")}/tip`, io))?.height);
  const newest = tops[tops.length - 1];
  if (!Number.isSafeInteger(tip) || tip - newest > MAX_LAG) throw new Error(`newest entry ${newest} is more than ${MAX_LAG} below the public tip ${tip}: regenerate the table`);
  return { entries: tops.length, newest, tip };
}

const flag = (argv, name) => { const i = argv.indexOf(name); return i < 0 ? undefined : argv[i + 1]; };

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const argv = process.argv.slice(2);
  const run = argv.includes("--check")
    ? check({ headers: flag(argv, "--headers"), rpc: flag(argv, "--rpc") }).then((r) => `anchors check passed: ${r.entries} entries, newest ${r.newest}, public tip ${r.tip}`)
    : generate({
      c1Text: argv[0] ? readFileSync(argv[0], "utf8") : "",
      base: process.env.HEADERS_BASE || "http://127.0.0.1:7777",
      write: argv.includes("--write"),
    }).then((r) => `${argv.includes("--write") ? "wrote" : "would write (run with --write)"} ${TABLE}: ${r.entries} entries, newest ${r.newest}`);
  run.then((m) => console.log(m), (e) => { console.error("update-spv-anchors:", e.message); process.exit(1); });
}
